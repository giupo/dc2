"""Ordnance carried by each aircraft type for each task.

The loadouts live in ``dynacamp/data/loadouts.json``: for every aircraft and
task, the stores on each pylon (with the game's weapon ids). The file is
generated from DCS' own pylon tables by ``dynacamp loadouts`` (needs pydcs), so
every store is valid for its pylon, and it is the single source of truth for:

* the briefing players receive (what to carry and use);
* the mission templates (:mod:`dynacamp.adapters.dcs.miz`), so AI flights fly
  with exactly the briefed ordnance;
* the rules (missiles in air combat, jamming pods): each store carries its
  :class:`StoreKind` and counts, set by the generator from the game's names
  (``adapters/dcs/data/weapons.toml``). This module never reads a store name
  except to show it.
"""

from __future__ import annotations

import json
from collections import Counter
from dataclasses import dataclass
from enum import StrEnum
from functools import cache
from pathlib import Path

from .air import Task

#: The loadouts file, generated by ``dynacamp loadouts``.
DATA = Path(__file__).parent / "data" / "loadouts.json"


class StoreKind(StrEnum):
    """What the rules care about in a store (``kind`` in the loadouts file)."""
    #: Radar-guided air-to-air missiles: ``count`` and ``range_m``.
    BVR = "bvr"
    #: Heat seekers: ``count``.
    WVR = "wvr"
    #: A self-protection jamming pod.
    ECM = "ecm"
    #: Anti-radiation missiles, fired by SEAD flights; ``count`` and ``range_m``.
    ARM = "arm"


@cache
def _data() -> dict:
    """The loadouts file (empty if it has not been generated).

    Returns:
        Loadouts by aircraft id, then by task.
    """
    if not DATA.exists():
        return {}
    return json.loads(DATA.read_text(encoding="utf-8"))["aircraft"]


def stores(aircraft: str, task: Task) -> list[dict]:
    """Stores on each pylon for an aircraft and task.

    Args:
        aircraft: Campaign aircraft id, e.g. ``"f16c"``.
        task: Task name, e.g. ``"SEAD"``.

    Returns:
        ``[{"pylon": n, "name": ..., "clsid": ..., "weight": kg}, ...]``, empty if unknown;
        missiles and pods also have ``kind`` (a :class:`StoreKind`), ``count`` and ``range_m``.
    """
    return list(_data().get(aircraft, {}).get(task, []))


def summary(aircraft: str, task: Task) -> list[tuple[str, int]]:
    """Stores grouped by name: ``[(store name, number of pylons), ...]``, heaviest use first.

    Args:
        aircraft: Campaign aircraft id.
        task: Task name.

    Returns:
        The store names with the number of pylons carrying them.
    """
    counts = Counter(s["name"] for s in stores(aircraft, task))
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))


def weight_kg(aircraft: str, task: Task) -> float:
    """Total weight of the stores, kg.

    Args:
        aircraft: Campaign aircraft id.
        task: Task name.

    Returns:
        The weight in kg (0 without a loadout).
    """
    return sum(float(s.get("weight", 0.0)) for s in stores(aircraft, task))


# ---------------------------------------------------------------- air-to-air missiles


@dataclass(frozen=True)
class AirToAir:
    """Air-to-air missiles of one aircraft for a task.

    Attributes:
        bvr: Radar-guided missiles.
        bvr_range_m: Launch range of the longest-reaching of them (0 without).
        wvr: Heat seekers.
    """
    bvr: int = 0
    bvr_range_m: float = 0.0
    wvr: int = 0


@cache
def air_to_air(aircraft: str, task: Task) -> AirToAir:
    """Air-to-air missiles one aircraft carries for a task (from its loadout).

    Args:
        aircraft: Campaign aircraft id.
        task: Task name; escorts carry the CAP load when they have none of their own.

    Returns:
        The BVR and WVR missile counts and the longest BVR reach.
    """
    loads = stores(aircraft, task) or (stores(aircraft, Task.CAP) if task == Task.ESCORT else [])
    bvr = wvr = 0
    reach = 0.0
    for s in loads:
        kind = s.get("kind")
        if kind == StoreKind.BVR:
            bvr += s["count"]
            reach = max(reach, s["range_m"])
        elif kind == StoreKind.WVR:
            wvr += s["count"]
    return AirToAir(bvr, reach, wvr)


@dataclass(frozen=True)
class AntiRadiation:
    """Anti-radiation missiles of one aircraft for a task.

    Attributes:
        count: Missiles.
        range_m: Launch range of the shortest-reaching of them (0 without): a
            flight fires its whole load from there.
    """
    count: int = 0
    range_m: float = 0.0


@cache
def anti_radiation(aircraft: str, task: Task) -> AntiRadiation:
    """Anti-radiation missiles one aircraft carries for a task (from its loadout).

    Args:
        aircraft: Campaign aircraft id.
        task: Task name.

    Returns:
        The count and the launch range.
    """
    arms = [s for s in stores(aircraft, task) if s.get("kind") == StoreKind.ARM]
    if not arms:
        return AntiRadiation()
    return AntiRadiation(sum(s["count"] for s in arms), min(s["range_m"] for s in arms))


@cache
def has_ecm_pod(aircraft: str, task: Task) -> bool:
    """True if the loadout carries a self-protection jamming pod (ALQ-131/184, SPS-141...).

    Args:
        aircraft: Campaign aircraft id.
        task: Task name.

    Returns:
        Whether a jamming pod is loaded.
    """
    return any(s.get("kind") == StoreKind.ECM for s in stores(aircraft, task))
